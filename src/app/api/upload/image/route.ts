import { NextRequest, NextResponse } from 'next/server';

export async function POST(request: NextRequest) {
  try {
    const formData = await request.formData();
    const file = formData.get('image') as File;
    
    if (!file) {
      return NextResponse.json({ error: 'No file provided' }, { status: 400 });
    }

    // Validate file type
    if (!file.type.startsWith('image/')) {
      return NextResponse.json({ error: 'File must be an image' }, { status: 400 });
    }

    // Validate file size (5MB max)
    if (file.size > 5 * 1024 * 1024) {
      return NextResponse.json({ error: 'File size must be less than 5MB' }, { status: 400 });
    }

    // For now, we'll use a placeholder URL since we don't have Cloudinary set up
    // In a real implementation, you would upload to Cloudinary or another service
    const placeholderUrl = `https://placehold.co/800x400/467EC7/ffffff?text=${encodeURIComponent(file.name)}`;
    
    return NextResponse.json({ 
      url: placeholderUrl,
      filename: file.name,
      size: file.size 
    });
  } catch (error) {
    console.error('Upload error:', error);
    return NextResponse.json({ error: 'Upload failed' }, { status: 500 });
  }
}
